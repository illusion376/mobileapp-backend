package io.illusion.domain.services.contracts

import domain.models.contracts.Player

interface PlayerService {

    /**
     * Возвращает профиль игрока по его уникальному идентификатору.
     *
     * Метод запрашивает «сырые» данные из репозитория базы данных,
     * производит автоматическую валидацию и пересчёт вычисляемых характеристик
     * (уровня и опыта) через игровой сервис, гарантируя актуальность данных.
     *
     * @param userId Уникальный идентификатор пользователя (игрока).
     * @return Объект [Player] с полностью валидными и готовыми к отображению данными,
     *         или null, если персонаж с таким ID не найден.
     */
    fun getPlayerProfile(userId: Int): Player?
}
